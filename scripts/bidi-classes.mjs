#!/usr/bin/env node
// Writes src/layout-engine/bidi-classes.ts: every code point's strong direction, from the Unicode
// Character Database's Bidi_Class with its defaults for unassigned code points (DerivedBidiClass),
// as a run-length table: `L` for Bidi_Class L, `R` for R and AL, `N` for every other class, each
// followed by its run's length in base 36.
//   node scripts/bidi-classes.mjs [path to @unicode/unicode-<version>]
// The data is not a dependency of this repository: install it first without saving
// (`npm install --no-save @unicode/unicode-17.0.0@2.1.0`), the Unicode version of Chromium's ICU.

import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const VERSION = '17.0.0';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const [given] = process.argv.slice(2);
const data = given ?? dirname(require.resolve(`@unicode/unicode-${VERSION}/package.json`));

const ranges = async (name) =>
  (await import(pathToFileURL(join(data, 'Bidi_Class', name, 'ranges.mjs')).href)).default;

const strong = [
  ...(await ranges('Left_To_Right')).map((range) => ({ ...range, kind: 'L' })),
  ...(await ranges('Right_To_Left')).map((range) => ({ ...range, kind: 'R' })),
  ...(await ranges('Arabic_Letter')).map((range) => ({ ...range, kind: 'R' })),
].sort((one, other) => one.begin - other.begin);

// The runs, each class's letter and length, with a run of `N` before each gap; touching runs of
// one letter joined.
const runs = [];
let at = 0;
const push = (kind, length) => {
  const last = runs.at(-1);
  if (last?.kind === kind) last.length += length;
  else runs.push({ kind, length });
};
for (const { begin, end, kind } of strong) {
  if (begin < at) throw new Error(`overlapping classes at ${begin.toString(16)}`);
  if (begin > at) push('N', begin - at);
  push(kind, end - begin);
  at = end;
}
if (at < 0x110000) push('N', 0x110000 - at);

const table = runs.map(({ kind, length }) => kind + length.toString(36)).join('');
const lines = (table.match(/.{1,92}/gu) ?? []).map((line) => `  '${line}'`);

writeFileSync(
  join(root, 'src/layout-engine/bidi-classes.ts'),
  `// Generated by scripts/bidi-classes.mjs from Unicode ${VERSION}'s Bidi_Class; do not edit.
// Every code point's strong direction as runs from U+0000: \`L\` for Bidi_Class L, \`R\` for R and
// AL, \`N\` for every other class, each followed by its run's length in base 36.

export const UNICODE_VERSION = '${VERSION}';

export const STRONG_RUNS =
${lines.join(' +\n')};
`,
);
console.log(`${String(runs.length)} runs, ${String(table.length)} characters`);
